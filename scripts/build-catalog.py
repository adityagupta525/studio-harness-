#!/usr/bin/env python3
"""build-catalog.py: the capability catalog the director routes from.

usage: build-catalog.py [--probe] [--check]
Reads agents/*.md and skills/*/SKILL.md front matter plus catalog/tools.json, writes catalog/capabilities.json
and docs/CATALOG.md. --probe runs each tool's check command on this machine and marks it available / missing
(the committed files are built without --probe). --check exits 1 if the committed files are stale. Stdlib only.
"""
import glob, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def front(path):
    t = open(path, encoding='utf-8').read()
    m = re.match(r'---\n(.*?)\n---', t, re.S)
    out = {}
    for line in (m.group(1).splitlines() if m else []):
        k, _, v = line.partition(':')
        if v: out[k.strip()] = v.strip()
    return out

def build(probe):
    agents = [dict(front(f), file=os.path.relpath(f, ROOT)) for f in sorted(glob.glob(os.path.join(ROOT, 'agents', '*.md')))]
    skills = [dict(front(f), file=os.path.relpath(f, ROOT)) for f in sorted(glob.glob(os.path.join(ROOT, 'skills', '*', 'SKILL.md')))]
    tools = json.load(open(os.path.join(ROOT, 'catalog', 'tools.json')))['tools']
    if probe:
        for t in tools:
            t['status'] = 'available' if subprocess.run(['bash', '-c', t['check']], capture_output=True).returncode == 0 else 'missing'
    cat = {'agents': [{k: a.get(k, '') for k in ('name', 'department', 'reports_to', 'description', 'file')} for a in agents],
           'skills': [{k: s.get(k, '') for k in ('name', 'description', 'file')} for s in skills],
           'tools': tools}
    md = ['# Capability catalog', '', '<!-- Generated by scripts/build-catalog.py from agents/, skills/ and catalog/tools.json. Do not edit by hand. -->', '',
          f"{len(cat['agents'])} agents · {len(cat['skills'])} skills · {len(tools)} external tools. Departments and roles: [docs/15](15-departments-and-orchestration.md).", '',
          '## Agents by department', '', '| Department | Agent | Reports to | Does |', '|---|---|---|---|']
    order = ["Director's office", 'Intelligence', 'Strategy', 'Growth & Platforms', 'Creative', 'Production', 'QA & Standards', 'Learning & Engineering']
    for a in sorted(cat['agents'], key=lambda a: (order.index(a['department']) if a['department'] in order else 99, a['name'])):
        md.append(f"| {a['department'] or '?'} | `{a['name']}` | {a['reports_to']} | {a['description'][:220]} |")
    md += ['', '## Skills (procedures)', '', '| Skill | Use when |', '|---|---|']
    md += [f"| `{s['name']}` | {s['description'][:240]} |" for s in cat['skills']]
    md += ['', '## External tools', '', '| Tool | Kind | Cost | Can | Used by' + (' | Status' if probe else '') + ' |', '|---|---|---|---|---|' + ('---|' if probe else '')]
    for t in tools:
        md.append(f"| `{t['id']}` | {t['kind']} | {t['cost']} | {t['can']} | {', '.join(t['used_by'])}" + (f" | {t['status']}" if probe else '') + ' |')
    return cat, '\n'.join(md) + '\n'

def main():
    probe, check = '--probe' in sys.argv, '--check' in sys.argv
    cat, md = build(probe and not check)
    j = json.dumps(cat, indent=1, ensure_ascii=False) + '\n'
    pj, pm = os.path.join(ROOT, 'catalog', 'capabilities.json'), os.path.join(ROOT, 'docs', 'CATALOG.md')
    if check:
        stale = [p for p, c in ((pj, j), (pm, md)) if not os.path.exists(p) or open(p, encoding='utf-8').read() != c]
        for p in stale: print(f'STALE {os.path.relpath(p, ROOT)}: run scripts/build-catalog.py')
        sys.exit(1 if stale else 0)
    if probe:
        print(md); return
    open(pj, 'w', encoding='utf-8').write(j); open(pm, 'w', encoding='utf-8').write(md)
    print(f"catalog: {len(cat['agents'])} agents, {len(cat['skills'])} skills, {len(cat['tools'])} tools")

if __name__ == '__main__':
    main()
